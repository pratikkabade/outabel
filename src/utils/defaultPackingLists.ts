export const generateDefaultPackingList = (numDays: number): PackingItem[] => {
  const days = Math.max(1, Math.round(numDays || 1));
  const template =
    days <= 2
      ? SHORT_TRIP_ITEMS
      : days <= 5
        ? MEDIUM_TRIP_ITEMS
        : EXTENDED_TRIP_ITEMS;

  const stamp = Date.now().toString(36);
  return template.map((entry, idx) => ({
    id: `pk-${stamp}-${idx + 1}`,
    text: entry.text,
    category: entry.category,
    packed: false,
  }));
};
